import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { IssueBody } from "@/components/IssueBody";
import { getIssue } from "@/lib/content";
import { renderIssueEmail, renderIssueText } from "@/lib/email";
import { forwardIssueUrl, forwardMailto, forwardedSubscribeUrl } from "@/lib/issue-present";
import { productivitySectionTopic } from "@/lib/schema";

describe("Option B scannable dashboard", () => {
  it("keeps Warehousing, jump chips, and forward links on the October 21 issue", () => {
    const issue = getIssue("aviation", "2026-10-21");
    expect(issue).toBeTruthy();
    if (!issue) return;

    const html = renderToStaticMarkup(createElement(IssueBody, { issue }));
    const email = renderIssueEmail(issue, { mode: "broadcast" });
    const text = renderIssueText(issue, { mode: "broadcast" });
    const mailto = forwardMailto(issue).replaceAll("&", "&amp;");

    expect(html).toContain('class="dash-hero"');
    expect(html).toContain('class="dash-grid"');
    expect(html).not.toContain('class="dash-split"');
    expect(html).not.toContain(issue.playbook?.title ?? "missing playbook");
    expect(html).not.toContain("Quick links");
    expect(html).toContain('class="glossary-table"');
    expect(html).toContain('href="#recruiting"');
    expect(html).toContain('href="#warehousing"');
    expect(html).toContain('id="warehousing"');
    expect(html).toContain('<span class="section-number" aria-hidden="true">06</span>');
    expect(html).toContain('<span class="section-title">Warehousing</span>');
    expect(html).not.toContain("jump-chip productivity");
    expect(html.match(/class="jump-chip"/g)?.length).toBe(8);
    expect(html).toContain(`<b>08</b> ${productivitySectionTopic}`);
    expect(html).toContain(">07</b> AOG Support");
    expect(html.match(/>CUSTOMIZE</g)).toHaveLength(2);
    expect(html).toContain(`href="${mailto}"`);
    expect(html.match(/>SUBSCRIBE</g)).toHaveLength(2);
    expect(html.match(/>FORWARD TO A COLLEAGUE</g)).toHaveLength(2);
    expect(html.match(/>READ ON WEB</g)).toHaveLength(2);
    expect(html.match(/class="issue-actions"/g)).toHaveLength(2);
    expect(html).toContain('href="/join"');
    expect(html).toContain(`href="/aviation/issues/${issue.date}"`);
    expect(html).toContain(" • ");
    expect(html.indexOf(">SUBSCRIBE<")).toBeLessThan(html.indexOf(">FORWARD TO A COLLEAGUE<"));
    expect(html.indexOf(">FORWARD TO A COLLEAGUE<")).toBeLessThan(html.indexOf(">READ ON WEB<"));
    expect(html).not.toContain("Forward this");
    expect(html).not.toContain("Forwarded this");
    expect(html.indexOf("Jump to")).toBeLessThan(html.indexOf(issue.lead.title));
    expect(html.indexOf(">What We Do<")).toBeLessThan(html.indexOf("Make Vizonix yours."));
    expect(html.indexOf("Make Vizonix yours.")).toBeLessThan(html.indexOf('href="/preferences">Update my preferences</a>'));
    expect(html.indexOf('href="/preferences">Update my preferences</a>')).toBeLessThan(html.indexOf(issue.lead.title));
    expect(html.match(/class="what-we-do"/g)).toHaveLength(1);
    expect(html).not.toContain(">Customize<");
    expect(html.indexOf(issue.lead.title)).toBeLessThan(html.indexOf('aria-hidden="true">01<'));
    expect(html.indexOf('class="slot house"')).toBeLessThan(html.indexOf(">What We Do<"));
    expect(html).toContain("Make Vizonix yours. Choose which sections you get, drop the ones you don");
    expect(html).toContain('href="/preferences">Update my preferences</a>');
    expect(html).not.toContain("Sign-Up Now");
    expect(html).not.toContain("Suggest a topic");
    expect(html).not.toContain('name="email"');
    expect(html).not.toContain("Pick your topics - get only the sections you care about");
    expect(html).not.toContain('href="/join">Customize your issue</a>');
    expect(html).not.toContain('class="ramp-heading"');
    expect(html.indexOf('aria-hidden="true">08<')).toBeLessThan(html.indexOf('class="issue-toolbox"'));
    expect(html.indexOf('class="issue-toolbox"')).toBeLessThan(html.indexOf('class="glossary-heading"'));
    expect(decodeURIComponent(forwardMailto(issue))).toContain(forwardIssueUrl(issue));
    expect(forwardIssueUrl(issue)).toContain("?src=forward");

    expect(email).toContain('width="640"');
    expect(email).toContain("max-width:640px");
    expect(email).toContain(".vz-wrap { width: 100% !important; max-width: 100% !important; }");
    expect(email).not.toContain('width="50%"');
    expect(email).toContain(".vz-stack");
    expect(email).toContain("background-color:#d5dbe3");
    expect(email).toContain("border:1px solid #cfd5de");
    expect(email).toContain("border-radius:12px");
    expect(email).toContain("<!--[if mso]>");
    expect(email).toContain(">SUBSCRIBE<");
    expect(email).toContain(">FORWARD TO A COLLEAGUE<");
    expect(email).toContain(">READ ON WEB<");
    expect(email).toContain(" • ");
    expect(email).toContain("text-align:center");
    expect(email).toContain("white-space:nowrap");
    expect(email).toContain(`href="${forwardedSubscribeUrl}"`);
    expect(forwardedSubscribeUrl).toBe("https://www.vizonix.com/join?src=forwarded");
    expect(email.indexOf(">SUBSCRIBE<")).toBeLessThan(email.indexOf(">FORWARD TO A COLLEAGUE<"));
    expect(email.indexOf(">FORWARD TO A COLLEAGUE<")).toBeLessThan(email.indexOf(">READ ON WEB<"));
    expect(email.indexOf(">READ ON WEB<")).toBeLessThan(email.indexOf(">CUSTOMIZE<"));
    expect(email.indexOf(">SUBSCRIBE<")).toBeLessThan(email.indexOf(issue.lead.title));
    expect(email.match(/>SUBSCRIBE</g)).toHaveLength(2);
    expect(email.match(/>FORWARD TO A COLLEAGUE</g)).toHaveLength(2);
    expect(email.match(/>READ ON WEB</g)).toHaveLength(2);
    expect(email.lastIndexOf(">FORWARD TO A COLLEAGUE<")).toBeGreaterThan(email.indexOf("AI Glossary"));
    expect(email).not.toContain("Forwarded this? Subscribe!");
    expect(email).not.toContain(">Forward this<");
    expect(email).not.toContain("Read on the web");
    expect(email).not.toContain("Read this issue on the web");
    expect(email).toContain(`href="${mailto}"`);
    expect(email).not.toMatch(/href="#/);
    expect(email).not.toContain("Jump to");
    expect(email).not.toContain(">07</b> AOG Support</a>");
    expect(email).toContain(">06</td>");
    expect(email).toContain(">Warehousing</td>");
    expect(email).toContain(">AOG Support: Parts, Rotables &amp; Technicians</td>");
    expect(email.match(/>CUSTOMIZE</g)).toHaveLength(2);
    expect(email.indexOf("background-color:#d5dbe3")).toBeLessThan(email.indexOf("background:#13233b"));
    expect(email.indexOf("What We Do")).toBeLessThan(email.indexOf("Make Vizonix yours."));
    expect(email.indexOf("Make Vizonix yours.")).toBeLessThan(email.indexOf(">Update my preferences</a>"));
    expect(email.indexOf(">Update my preferences</a>")).toBeLessThan(email.indexOf(issue.lead.title));
    expect(email.match(/>What We Do</g)).toHaveLength(1);
    expect(email).not.toContain(">Customize</h2>");
    expect(email.indexOf(issue.lead.title)).toBeLessThan(email.indexOf(">01</td>"));
    expect(email).toContain("Make Vizonix yours. Choose which sections you get");
    expect(email).toContain(">Update my preferences</a>");
    expect(email).toContain('href="https://vizonix.com/preferences"');
    expect(email).not.toContain("Sign-Up Now");
    expect(email).not.toContain("Send confirmation");
    expect(email).not.toContain("Pick your topics - get only the sections you care about");
    expect(email).not.toContain(">Customize your issue</a>");
    expect(email.match(/Today&#39;s top story/g)).toHaveLength(1);
    const storyLabel = email.indexOf("Today&#39;s top story");
    const titleCard = email.indexOf(`${issue.subject}<span`);
    expect(storyLabel).toBeGreaterThan(email.indexOf(">V</a>"));
    expect(storyLabel).toBeLessThan(titleCard);
    expect(titleCard).toBeLessThan(email.indexOf(">SUBSCRIBE<"));
    const kicker = email.slice(Math.max(0, storyLabel - 500), titleCard);
    expect(kicker).toContain("text-transform:uppercase");
    expect(kicker).toContain("letter-spacing:0.12em");
    expect(kicker).not.toContain(issue.lead.title);
    expect(email).toContain("Contact us at: <a href=\"mailto:admin@vizonix.com\"");
    expect(email).not.toContain("Manage your topics");
    expect(email).not.toContain(">The Ramp</td>");
    expect(email.indexOf(`>${productivitySectionTopic}</td>`)).toBeLessThan(email.indexOf("The Vizonix Toolbox"));
    expect(email.indexOf("The Vizonix Toolbox")).toBeLessThan(email.indexOf(">AI Glossary</h2>"));
    expect(text.indexOf("WHAT WE DO")).toBeLessThan(text.indexOf("you. Make Vizonix yours."));
    expect(text.indexOf("you. Make Vizonix yours.")).toBeLessThan(text.indexOf("Update my preferences: https://vizonix.com/preferences"));
    expect(text.indexOf("Update my preferences: https://vizonix.com/preferences")).toBeLessThan(text.indexOf(issue.lead.title));
    expect(text).not.toMatch(/^CUSTOMIZE$/m);
    expect(text.indexOf(issue.lead.title)).toBeLessThan(text.indexOf("RECRUITING"));
    expect(text).toContain("Make Vizonix yours. Choose which sections you get, drop the ones you don't need, and change it anytime.");
    expect(text).toContain("Update my preferences: https://vizonix.com/preferences");
    expect(text).not.toContain("SIGN-UP NOW");
    expect(text).not.toContain("Pick your topics - get only the sections you care about");
    expect(text).not.toContain("Customize your issue:");
    expect(text).toContain("TODAY'S TOP STORY");
    expect(text).toContain("Contact us at: admin@vizonix.com");
    expect(text).not.toContain("Manage your topics");
    expect(text).not.toContain("THE RAMP");
    expect(text.indexOf("QUICK LINKS")).toBeLessThan(text.indexOf("The Vizonix Toolbox"));
    expect(text.indexOf("The Vizonix Toolbox")).toBeLessThan(text.indexOf("AI GLOSSARY"));

    const actionLine = `SUBSCRIBE: ${forwardedSubscribeUrl} • FORWARD TO A COLLEAGUE: ${forwardMailto(issue)} • READ ON WEB: https://vizonix.com/aviation/issues/${issue.date} • CUSTOMIZE: https://vizonix.com/preferences`;
    expect(text.indexOf(actionLine)).toBeLessThan(text.indexOf(issue.lead.title));
    expect(text.split(actionLine).length - 1).toBe(2);
    expect(text.lastIndexOf(actionLine)).toBeGreaterThan(text.indexOf("AI GLOSSARY"));
    expect(text).not.toContain("Forward this");
    expect(text).not.toContain("Forwarded this");
    expect(text).not.toContain("Read on the web");
    expect(text).not.toContain("Read this issue on the web");
    expect(html).not.toMatch(/[\u2013\u2014]/);
    expect(email).not.toMatch(/[\u2013\u2014]/);
    expect(text).not.toMatch(/[\u2013\u2014]/);
  });
});
